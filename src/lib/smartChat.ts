export function getSmartReply(message: string) {
  const text = message.toLowerCase();

  if (text.includes("дорого") || text.includes("цена")) {
    return "На возражение «дорого» не спорим. Ответ: «Понимаю. Давайте разберём, что входит в стоимость: подбор, проверенные поставщики, экономия времени и снижение риска ошибок. Также можем посмотреть варианты оптимизации бюджета.»";
  }

  if (text.includes("первый звонок") || text.includes("звонок")) {
    return "На первом звонке задача менеджера — не продавать сразу, а понять ситуацию клиента. Сценарий: представиться, уточнить объект, сроки, бюджет, кто принимает решение и какой следующий шаг удобен.";
  }

  if (text.includes("возраж")) {
    return "С возражениями работаем по схеме: выслушать → признать сомнение → уточнить причину → показать ценность → предложить следующий шаг.";
  }

  if (text.includes("комплектац")) {
    return "Комплектация под ключ — это помощь клиенту в подборе и закупке решений для объекта: мебель, свет, сантехника, материалы, декор. Главная ценность — экономия времени и снижение ошибок.";
  }

  if (text.includes("follow") || text.includes("после встречи")) {
    return "После встречи отправь follow-up: поблагодари за время, кратко зафиксируй задачу, договорённости и следующий шаг. Это повышает доверие и снижает риск потери клиента.";
  }

  if (text.includes("скрипт")) {
    return "Пример скрипта: «Здравствуйте, меня зовут Анна, Студия комплектации. Подскажите, пожалуйста, какой объект вы сейчас комплектуете и на каком этапе находитесь?»";
  }

  return "Я могу помочь по темам: первый звонок, возражение «дорого», комплектация под ключ, follow-up, скрипты общения и работа с клиентом.";
}